async page => {
  const checks = [];
  const errors = [];
  const apiRequests = [];
  const check = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/api\.(anthropic|groq)\.com/.test(request.url())) apiRequests.push(request.url()); });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:5173/#subchefe');
  await page.reload();
  check(await page.locator('iframe').count() === 0, 'Demo carrega somente quando solicitada');
  await page.getByRole('button', { name: 'Experimentar o app', exact: true }).click();
  const frame = page.frameLocator('iframe');
  await frame.getByRole('button', { name: 'Fazer check-in', exact: true }).waitFor({ state: 'visible' });
  await frame.locator('body').evaluate(() => document.fonts.ready);
  check(await frame.locator('body').evaluate(() => document.fonts.check('16px Nunito_400Regular') && document.fonts.check('16px ionicons')), 'Fontes e ícones reais do app carregam');
  check((await frame.locator('body').innerText()).includes('Média dos últimos 7 dias'), 'Tela inicial apresenta pontuação calculada');
  await page.getByRole('button', { name: 'Check-in', exact: true }).click();
  await frame.getByRole('textbox', { name: 'Momentos do dia', exact: true }).waitFor({ state: 'visible' });
  await frame.getByText('Bom', { exact: true }).click();
  await frame.getByText('Acordei de manhã', { exact: true }).click();
  await frame.getByText('Peguei sol / caminhei', { exact: true }).click();
  await frame.getByText('1 h', { exact: true }).click();
  await frame.getByText('2', { exact: true }).click();
  await frame.getByRole('textbox', { name: 'Momentos do dia', exact: true }).fill('Registro fictício para testar a demonstração.');
  await frame.getByRole('button', { name: 'Salvar dia', exact: true }).click();
  await frame.getByText('Continuar', { exact: true }).click();
  await frame.getByRole('button', { name: 'Editar check-in', exact: true }).waitFor({ state: 'visible' });
  check(true, 'Check-in é salvo e atualiza a tela inicial');
  await page.getByRole('button', { name: 'Progresso', exact: true }).click();
  await frame.getByText('Evolução', { exact: true }).waitFor({ state: 'visible' });
  const progress = await frame.locator('body').innerText();
  check(progress.includes('Comparativos') && progress.includes('22/22'), 'Gráficos e comparativos incorporam o novo registro');
  await frame.getByText('Análise com IA', { exact: true }).click();
  await frame.getByText('Exemplo de análise', { exact: true }).waitFor({ state: 'visible' });
  check((await frame.locator('body').innerText()).includes('Conteúdo ilustrativo fixo'), 'Análise é apresentada como exemplo local');
  check(apiRequests.length === 0, 'Demonstração não chama APIs de IA');
  check(await frame.locator('body').evaluate(() => !Object.keys(localStorage).some(key => key.startsWith('subchefe:'))), 'Registros ficam em memória');
  await page.getByRole('button', { name: 'Reiniciar demo', exact: true }).click();
  await frame.getByRole('button', { name: 'Fazer check-in', exact: true }).waitFor({ state: 'visible' });
  check(true, 'Reiniciar restaura os dados fictícios originais');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.demo-phone').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'qa/subchefe-final-mobile.png' });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Demonstração cabe no celular');
  const phone = await page.locator('.demo-phone').boundingBox();
  check(phone.x >= 0 && phone.x + phone.width <= 390, 'Celular não é cortado pelo contêiner');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#subchefe').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'qa/subchefe-final-desktop.png' });
  check(errors.length === 0, 'Sem erros JavaScript na navegação e no check-in');
  return { checks, errors, apiRequests };
}
