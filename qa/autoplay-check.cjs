async page => {
  const checks = [];
  const errors = [];
  const check = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:5173/');
  await page.evaluate(() => localStorage.setItem('portfolio-motion', 'paused'));
  await page.reload();
  await page.locator('.interactive-avatar.is-greeting').waitFor({ state: 'visible' });
  check(await page.locator('html').getAttribute('data-motion') === 'running', 'Abre automaticamente mesmo com preferência antiga de pausa');
  check(await page.getByRole('button', { name: 'Acenar com o avatar de Marcus', exact: true }).isEnabled(), 'Botão do avatar funciona com reduzir movimento no sistema');
  check(await page.locator('.interactive-avatar__float').evaluate(node => getComputedStyle(node).animationName === 'avatarIdle' && getComputedStyle(node).animationPlayState === 'running'), 'Movimento contínuo começa sem clique');
  check(await page.locator('.kinetic-title__code').evaluate(node => Number(getComputedStyle(node).opacity) > 0 && getComputedStyle(node).animationPlayState === 'running'), 'Código dentro das letras começa sem clique');
  check(await page.evaluate(() => localStorage.getItem('portfolio-motion') === null), 'Escolha antiga que bloqueava a animação é limpa');
  await page.locator('.motion-toggle').click();
  await page.waitForFunction(() => document.querySelector('.interactive-avatar').dataset.paused === 'true');
  check(await page.locator('.interactive-avatar__float').evaluate(node => getComputedStyle(node).animationName === 'none'), 'Pausa manual interrompe o avatar');
  check(await page.locator('.kinetic-title__code').evaluate(node => getComputedStyle(node).opacity === '0'), 'Pausa manual interrompe as letras');
  await page.getByRole('button', { name: 'Acenar com o avatar de Marcus', exact: true }).click();
  await page.locator('.interactive-avatar.is-greeting').waitFor({ state: 'visible' });
  check(await page.locator('html').getAttribute('data-motion') === 'running', 'O botão do avatar retoma as animações');
  await page.locator('.motion-toggle').click();
  await page.reload();
  await page.locator('.interactive-avatar.is-greeting').waitFor({ state: 'visible' });
  check(await page.locator('html').getAttribute('data-motion') === 'running', 'Nova visita começa animada');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.locator('.interactive-avatar.is-greeting').waitFor({ state: 'visible' });
  check(await page.getByRole('button', { name: 'Acenar com o avatar de Marcus', exact: true }).isEnabled(), 'Animação automática também funciona no tamanho de celular');
  await page.screenshot({ path: 'qa/autoplay-mobile.png' });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.locator('.interactive-avatar.is-greeting').waitFor({ state: 'visible' });
  await page.screenshot({ path: 'qa/autoplay-desktop.png' });
  check(errors.length === 0, 'Sem erros JavaScript no autoplay e na retomada');
  return { checks, errors };
}
